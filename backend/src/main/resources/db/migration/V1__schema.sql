create table movie (
    id           bigint generated by default as identity primary key,
    title        varchar(255) not null,
    release_year integer,
    overview     varchar(2000),
    poster_url   varchar(255)
);

create table movie_genre (
    movie_id bigint      not null references movie (id) on delete cascade,
    genre    varchar(255) not null
);
create index movie_genre_movie_idx on movie_genre (movie_id);
create index movie_genre_genre_idx on movie_genre (genre);

create table app_user (
    id            bigint generated by default as identity primary key,
    username      varchar(255) not null unique,
    password_hash varchar(255) not null
);

create table rating (
    id         bigint generated by default as identity primary key,
    user_id    bigint           not null references app_user (id) on delete cascade,
    movie_id   bigint           not null references movie (id) on delete cascade,
    score      double precision not null check (score between 0.5 and 5.0),
    review     varchar(2000),
    updated_at timestamp(6) with time zone,
    unique (user_id, movie_id)
);
-- unique(user_id, movie_id) already indexes user_id lookups; PostgreSQL does not index FKs by itself
create index rating_movie_idx on rating (movie_id);

create table watchlist_item (
    id       bigint generated by default as identity primary key,
    user_id  bigint not null references app_user (id) on delete cascade,
    movie_id bigint not null references movie (id) on delete cascade,
    added_at timestamp(6) with time zone,
    unique (user_id, movie_id)
);
